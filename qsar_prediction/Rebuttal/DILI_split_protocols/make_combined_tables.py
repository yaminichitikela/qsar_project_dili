r"""One LaTeX table per split protocol, with Stage 1 (Proxy-only) and Stage 2
(Proxy+DILI) stacked in the same table, for one classification cutoff.

Reads results/summary.csv (written by aggregate.py), Held-223 rows only.
Tables are scaled to \linewidth with \resizebox (needs graphicx).
Bold marks the best value per column within each stage block; where means tie
at the precision shown, the smaller SD wins (same rule as the other tables).

Usage: python make_combined_tables.py [cutoff]      (default 0.5)
Output: results/tables_dili_split_protocols_cpt<NN>_combined.tex
"""
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from aggregate import GROUPS, METRICS, TEX_NAME, fmt

PROTOS = [
    ('random_repeat', 'repeated random 80/10/10 splits (5 repeats)', 'random'),
    ('cv', '10-fold cross-validation (10 folds)', 'cv'),
    ('scaffold', 'repeated Murcko-scaffold 8:1:1 splits (5 repeats)', 'scaffold'),
]
STAGES = [(1, 'Stage 1 (Proxy-only)'), (2, 'Stage 2 (Proxy+DILI)')]


def best_per_column(s):
    best = {}
    for m in METRICS:
        nd = 2 if m in ('Sensitivity', 'Specificity', 'CCR') else 4
        k = s[[f'{m}_mean', f'{m}_sd']].copy()
        k['r'] = k[f'{m}_mean'].round(nd)
        best[m] = k.sort_values(['r', f'{m}_sd'], ascending=[False, True]).index[0]
    return best


def table(summ, proto, desc, tag, cpt):
    L = [r'\begin{table}[htbp]', r'\centering', r'\footnotesize',
         r'\setlength{\tabcolsep}{3.5pt}',
         rf'\caption{{DILI prediction performance, {desc}, Stage 1 (Proxy-only) and '
         rf'Stage 2 (Proxy+DILI). Training sets were downsampled to 1:1. Mean $\pm$ '
         rf'standard deviation over splits on the fixed Held-223 external test set; '
         rf'classification cutoff {cpt:.2f}. Sensitivity, specificity and CCR are '
         rf'percentages. Best value per column within each stage in bold; where means '
         rf'tie at the precision shown, the smaller standard deviation is taken as better.}}',
         rf'\label{{tab:dili_{tag}_cpt{int(round(cpt * 100))}_combined}}',
         r'\resizebox{\linewidth}{!}{%', r'\begin{tabular}{lccccccc}', r'\hline',
         r'Model & Sensitivity & Specificity & CCR & ROC-AUC & PR-AUC & MCC & F1 \\',
         r' & (\%) & (\%) & (\%) & & & & \\',
         r'\hline']
    for i, (stage, sname) in enumerate(STAGES):
        s = summ[(summ.Protocol == proto) & (summ.Stage == stage)].set_index('Model')
        best = best_per_column(s)
        if i:
            L.append(r'\hline')
        L.append(rf'\multicolumn{{8}}{{c}}{{\textbf{{{sname}}}}} \\')
        L.append(r'\hline')
        for gname, members in GROUPS:
            present = [x for x in members if x in s.index]
            if not present:
                continue
            L.append(rf'\multicolumn{{8}}{{l}}{{\textit{{{gname}}}}} \\')
            for mod in present:
                cells = []
                for m in METRICS:
                    c = fmt(m, s.loc[mod, f'{m}_mean'], s.loc[mod, f'{m}_sd'])
                    cells.append(rf'\textbf{{{c}}}' if best[m] == mod else c)
                L.append(rf'\quad {TEX_NAME.get(mod, mod)} & ' + ' & '.join(cells) + r' \\')
    L += [r'\hline', r'\end{tabular}}', r'\end{table}', '']
    return '\n'.join(L)


def main():
    cpt = float(sys.argv[1]) if len(sys.argv) > 1 else 0.5
    summ = pd.read_csv(os.path.join(HERE, 'results', 'summary.csv'))
    summ = summ[(summ.Split == 'test') & ((summ.CPT - cpt).abs() < 1e-9)]
    out = [f'% DILI split protocols, Stage 1 and Stage 2 combined, cutoff {cpt:.2f}.',
           '% Held-223 fixed test set; generated by DILI_split_protocols/make_combined_tables.py',
           '']
    out += [table(summ, p, d, t, cpt) for p, d, t in PROTOS]
    path = os.path.join(HERE, 'results',
                        f'tables_dili_split_protocols_cpt{int(round(cpt * 100))}_combined.tex')
    with open(path, 'w') as fh:
        fh.write('\n'.join(out))
    print(f'-> {path}')


if __name__ == '__main__':
    main()
